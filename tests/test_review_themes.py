"""Тесты разметки тем отзывов: морфология и защита от ложных срабатываний.

Словарь тем в reviews_dash писался основами через пробел («скрыт комисс»), но
сравнивался буквальной подстрокой — «скрытая комиссия» не совпадала, и темы
находили от пятой части до половины своих отзывов. Тесты фиксируют, что основа
раскрывается, а короткие служебные слова остаются буквальными.

БД не нужна: match_themes и _stem_rx — чистые функции над строкой.
"""
import re

import pytest

from bank_audit.rag.reviews_dash import THEMES, _stem_rx, _theme_rx, match_themes


def keys(text: str) -> set[str]:
    return {t["key"] for t in match_themes(text)}


# (текст отзыва, тема, которая обязана сработать)
MORPHOLOGY = [
    ("Программа долгосрочных сбережений: деньги пропали", "deposit"),
    ("Оформили ПДС без моего ведома", "deposit"),
    ("Открыл накопительный счёт, потом накопительные счета закрыли", "deposit"),
    ("Скрытая комиссия за обслуживание", "fees"),
    ("Скрытые платежи и скрытых условий полно", "fees"),
    ("Повышение тарифов без уведомления", "fees"),
    ("Подали на банкротство, кредитная история испорчена", "bankruptcy"),
    ("Финансового управляющего назначили в декабре", "bankruptcy"),
    ("Исполнительный лист, приставы списали прожиточный минимум", "enforcement"),
    ("Повышение ставки по действующему кредиту", "rate"),
    ("Изменил условия в одностороннем порядке", "rate"),
    ("Внесение наличных через банкомат не прошло", "atm"),
    ("Выдача наличных недоступна третий день", "atm"),
    ("Кредитные каникулы не дали", "hardship"),
    ("Урегулирование задолженности затянули", "hardship"),
    ("Свидетельства о смерти им мало", "inheritance"),
    ("Бонусные баллы сгорели", "loyalty"),
    ("Написал жалобу в прокуратуру", "escalation"),
    ("Обратился в Центральный банк", "escalation"),
    ("Страховку без спроса навесили", "insurance"),
    ("Подключил без согласия платную опцию", "missell"),
]

# то, что раскрытие основ НЕ должно начать ловить
FALSE_POSITIVES = [
    ("Мои жалобы все игнорируют", "escalation"),      # «жалоб в» не должно съесть «все»
    ("Комиссия задолженности не начислена", "fees"),  # «комисси за» не должно съесть «задолженности»
]


@pytest.mark.parametrize("text,theme", MORPHOLOGY)
def test_stem_matches_word_forms(text, theme):
    assert theme in keys(text), f"тема {theme} не сработала на «{text}»"


@pytest.mark.parametrize("text,theme", FALSE_POSITIVES)
def test_short_words_stay_literal(text, theme):
    assert theme not in keys(text), f"ложное срабатывание {theme} на «{text}»"


def test_abbreviation_needs_word_boundary():
    """« пдс» с ведущим пробелом означает границу слова, а не пробел буквально:
    «(ПДС)» и «ПДС.» обязаны совпадать, середина другого слова — нет."""
    rx = re.compile(_stem_rx(" пдс", r"\b"), re.I)
    assert rx.search("условия (ПДС) поменяли")
    assert rx.search("перевёл в ПДС.")
    assert not rx.search("депдским способом")


def test_every_pattern_compiles_for_both_engines():
    """Один словарь собирается в два синтаксиса: \\b для Python, \\y для Postgres.
    Питоновскую ветку проверяем компиляцией, постгресовую — тем, что строка
    отличается ровно границей слова и больше ничем."""
    for t in THEMES:
        py = _theme_rx(t, r"\b")
        pg = _theme_rx(t, r"\y")
        re.compile(py, re.I)
        assert py.replace(r"\b", "\x00") == pg.replace(r"\y", "\x00"), t["key"]


def test_multilabel_still_works():
    """Темы мультилейбл — один отзыв может попасть в несколько."""
    got = keys("Навязали страховку при кредите и подняли ставку, пишу жалобу в суд")
    assert {"insurance", "rate", "escalation"} <= got
