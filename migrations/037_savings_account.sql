-- 037: накопительные счета — отдельная категория витрины.
-- Аудит 11.08.2026: 55 накопительных счетов лежали внутри «Вкладов» и
-- ранжировались как срочные депозиты. Это разные продукты: у накопительного
-- ставка плавающая, срока нет, начисление зависит от остатка и трат — сравнение
-- их в одном ранжире искажает и медиану вкладов, и позицию банка.
-- Категория savings_account уже есть в enum product_category (миграция 004).
-- NB: одиночного знака процента в файле быть не должно (exec_driver_sql).

-- Переносим уже накопленное. Уникальный ключ product_offer — (bank_id,
-- category, external_id), поэтому смена категории безопасна: коллизия
-- возможна только если у банка есть оффер с тем же external_id уже в
-- savings_account, чего до этой миграции быть не могло.
UPDATE product_offer
   SET category = 'savings_account'
 WHERE category = 'deposit'
   AND (title ~* 'накопительн' OR title ~* 'сберегательн\s+сч[её]т' OR title ~* '\mнакопит\M');

-- Подсегмент у накопительных не нужен, а сегмент оставляем как есть
-- (детские и премиальные накопительные встречаются).
