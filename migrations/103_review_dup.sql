-- Копии одного отзыва на разных площадках (rag/review_dedup.py): автор пишет одну
-- историю на banki.ru, sravni и finuslugi — это одна жалоба, а не три. Копия
-- ссылается на каноническую строку (из корпуса banki.ru, иначе самую раннюю);
-- у канонической и у одиночного отзыва dup_of пуста. Строки не удаляются —
-- счётчики жалоб берут строки с пустой dup_of.
ALTER TABLE review_index ADD COLUMN IF NOT EXISTS dup_of text;

-- Копий — малая доля индекса, поэтому индекс частичный. Нужен проверке ссылок
-- (каноническая строка пропала — копия снова считается) и выборке копий одной истории.
CREATE INDEX IF NOT EXISTS review_index_dup_of ON review_index (dup_of) WHERE dup_of IS NOT NULL;
