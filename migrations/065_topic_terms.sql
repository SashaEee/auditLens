-- Опорные слова позиции таксономии: чем клиент её называет.
--
-- ЗАЧЕМ. Векторная разметка ставит КАЖДОМУ обращению ближайшую позицию, даже
-- когда обращение вообще не о продукте. Замер: у редких инструментов это даёт
-- многократный перебор — обезличенные металлические счета получили 1970 меток
-- при 48 обращениях, где слово вообще встречается.
--
-- Ни абсолютный порог, ни отрыв от второй позиции этого не режут: при любой
-- отсечке верные позиции теряют столько же, сколько ложные. Единственный
-- сигнал, который в этом проекте раз за разом оказывался честным, — словесный:
-- упоминает ли текст то, о чём мы утверждаем.
--
-- Вывести опорные слова из названия автоматически не выходит: у позиции
-- «Вклад (депозит)» самое редкое слово названия — «депозит», и поддержка
-- занижается в двадцать раз. Поэтому слова называет модель, читавшая корпус,
-- а проверяет их архив — тот же приём, что при расширении поисковых запросов.
--
-- NB: знак процента в комментариях миграций не ставить (exec_driver_sql).

ALTER TABLE review_topic_def ADD COLUMN IF NOT EXISTS terms TEXT[];

COMMENT ON COLUMN review_topic_def.terms IS
    'Слова, которыми клиенты называют эту позицию. Нужны, чтобы отличить '
    'позицию, которую называют прямо, от той, которую только описывают.';
