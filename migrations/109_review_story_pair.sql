-- 109: решения «одна ли это история» для пограничных пар групп «Сюжетов»
-- (rag/review_stories.py, склейка пограничных групп).
--
-- Было. Порог сходства изложений 0,84 рвал одну историю на части: у Сбера три
-- сюжета «лишили льготы семейной ипотеки» со средним сходством 0,82–0,83. Ниже
-- порога сходство одну историю от соседней не отличает (0,81 — «ставку подняли
-- после отказа от подписки» против «после смены страховки», а это разные).
--
-- Стало. Пары групп в полосе от нижней границы до порога решает модель; решение
-- хранится здесь по паре медоидов (адреса жалоб, a < b), и суточный прогон не
-- спрашивает заново: сюжеты не склеиваются и не расклеиваются от прогона к прогону.
-- Медоид сменился — пара новая, вопрос задаётся снова.
--
-- NB: знак процента в комментариях миграций не ставить — накатываются через
-- exec_driver_sql, psycopg считает его началом плейсхолдера.

SET lock_timeout = '3s';

CREATE TABLE IF NOT EXISTS review_story_pair (
    a     text        NOT NULL,                 -- медоид одной группы (меньший адрес)
    b     text        NOT NULL,                 -- медоид другой
    same  boolean     NOT NULL,                 -- одна история
    model text,                                 -- кто решил
    at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (a, b)
);
