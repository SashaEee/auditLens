-- Аудит-дело: «В дело» отовсюду (этап 4).
--
-- Кроме жалоб и документов в дело теперь приобщают отчёты и ответы
-- ИИ-помощника, новости выпуска и продукты «Рынка». У каждого вида свои
-- данные для карточки — они лежат в meta:
--   report — название, вопрос, режим, короткий вывод (lead), автор и дата.
--            Сам текст в дело не копируется: он живёт в отчёте и в выгрузку
--            дела не попадает (огромный отчёт в приложении к проверке не нужен);
--   answer — короткий ответ ИИ, который отчётом не сохранялся: вопрос, текст,
--            источники;
--   news   — источник, дата, краткое «почему важно»;
--   offer  — снимок условий НА ДАТУ приобщения: ставка, сумма, срок, версия
--            условий. Витрина меняется, а доказательство — нет.
-- Только ADD ... IF NOT EXISTS: повтор безопасен.
ALTER TABLE audit_case_item ADD COLUMN IF NOT EXISTS meta JSONB;
