-- 039: структурированные условия оффера, извлечённые LLM.
--
-- ЗАЧЕМ. Регулярные выражения разбирают числа, но не смысл. Из-за этого две
-- витринные метрики врали аудитору:
--   • дебетовые карты: 124 банка из 163 стоят на «0 руб./год», и ранг вырожден.
--     Но «бесплатно всегда» и «бесплатно при обороте от 100 тыс./мес.» — разные
--     продукты, а в тарифе это написано прозой, которую регексп не разберёт;
--   • кредиты: минимальная ставка часто достижима только со страховкой или для
--     зарплатного клиента. Ранг по ней сравнивает рекламу с реальностью.
-- Извлечённые поля кладём ОТДЕЛЬНО от product_terms: это не тариф банка, а наша
-- интерпретация, и она не должна порождать версии SCD2 и попадать в историю
-- изменений как «банк поменял условия».
--
-- src_digest — хеш текста, из которого извлекали: пока текст тот же, повторно
-- LLM не зовём (обход всей витрины иначе стоил бы полного прогона каждый день).

CREATE TABLE IF NOT EXISTS offer_enrichment (
  offer_id    BIGINT PRIMARY KEY REFERENCES product_offer(offer_id) ON DELETE CASCADE,
  src_digest  TEXT        NOT NULL,
  payload     JSONB       NOT NULL DEFAULT '{}'::jsonb,
  model       TEXT,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Витрине нужен быстрый отбор «кто бесплатен без условий» и «чья ставка
-- требует страховки» — оба поля лежат в payload верхним уровнем.
CREATE INDEX IF NOT EXISTS offer_enrichment_free
    ON offer_enrichment ((payload->>'free_kind'));
CREATE INDEX IF NOT EXISTS offer_enrichment_stale
    ON offer_enrichment (updated_at);
