-- 031: признак регуляторной эскалации считается при индексации, а не при чтении.
--
-- Метрика «доля жалоб с угрозой уйти в ЦБ, суд, ФАС или прокуратуру» на вкладке
-- «Отзывы» — KPI, который краснеет на 12 и выше. Она собиралась регэкспом по
-- тексту отзыва во внешней базе. При переводе агрегатов на единый индекс текста
-- под рукой не оказалось (индекс хранит tsvector), и попытка выразить те же
-- паттерны через tsquery дала завышение вдвое: 30 против 16 на том же срезе.
--
-- Причина в том, что ограничителем в паттернах служили предлоги. «жалобу В» —
-- это жалоба, НАПРАВЛЕННАЯ куда-то; без предлога остаётся «жалоб», и метрика
-- начинает считать любой отзыв, где вообще есть слово «жалоба». Вернуть предлог
-- в запрос нельзя: русский словарь полнотекстового поиска выбрасывает его из
-- индекса как стоп-слово, и в tsvector его просто нет.
--
-- Поэтому признак вычисляется тем же регэкспом, но ОДИН РАЗ, когда текст ещё в
-- руках — при наполнении индекса. Чтение становится обычным count(*) FILTER,
-- а смысл метрики совпадает с тем, что считалось раньше.
--
-- NB: знак процента в комментариях миграций не ставить (exec_driver_sql).

ALTER TABLE review_index ADD COLUMN IF NOT EXISTS esc BOOLEAN;

-- Частичный индекс: строк с признаком меньшинство, а спрашивают всегда их
CREATE INDEX IF NOT EXISTS review_index_esc
    ON review_index (bank, dt DESC) WHERE esc;
