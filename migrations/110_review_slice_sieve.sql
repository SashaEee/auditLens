-- Стало. Лёгкая модель читает изложение каждой жалобы вне кандидатов по словам и
-- отмечает срезы, к которым она МОЖЕТ относиться; отмеченные становятся кандидатами,
-- решает каскад, как всегда. Строка на жалобу — один раз (пустой keys — «ни к одному»),
-- повторно жалоба не просеивается.
--
-- NB: знак процента в комментариях миграций не ставить — накатываются через
-- exec_driver_sql, psycopg считает его началом плейсхолдера.

SET lock_timeout = '3s';

CREATE TABLE IF NOT EXISTS review_slice_sieve (
    url   text        PRIMARY KEY,
    keys  text[]      NOT NULL DEFAULT '{}',    -- срезы, к которым жалоба может относиться
    model text,
    at    timestamptz NOT NULL DEFAULT now()
);
