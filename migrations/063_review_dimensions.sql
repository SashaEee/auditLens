-- Таксономия отзывов становится ДВУМЕРНОЙ: тема и продукт.
--
-- ЗАЧЕМ. Метка продукта приходит из корпуса площадки и там неверна: сверка
-- показала, что 86-93 процентов обращений ВСЕХ банков помечены «Обслуживание
-- юридических лиц», хотя по тексту это розница — кешбэк, перевыпуск карты,
-- блокировка сбережений, судебный приказ. У одного банка при 19 тыс. обращений
-- метка «Вклад» стоит у двух. Исходная база доступна только на чтение и других
-- полей продукта не содержит, поэтому продукт нужно выводить из текста самим.
--
-- Машинерия для этого уже есть и проверена на темах: модель читает корпус и
-- называет категории, вектор относит отзыв к категории, SQL считает агрегаты.
-- Второй такой же модуль означал бы вторую копию всех граблей — от нормировки
-- по своим сигмам до ограничения ранга. Поэтому у категории появляется
-- ИЗМЕРЕНИЕ, а машина остаётся одна.
--
-- Разметка (review_topic_label) НЕ меняется: измерение однозначно определяется
-- topic_id, и лишняя колонка там была бы избыточной.
--
-- NB: знак процента в комментариях миграций не ставить (exec_driver_sql).

ALTER TABLE review_topic_def
    ADD COLUMN IF NOT EXISTS dim TEXT NOT NULL DEFAULT 'theme';

-- Поколения нумеруются ВНУТРИ измерения, поэтому старый ключ (version, key)
-- сталкивал бы тему и продукт с одинаковым слагом в одном поколении.
ALTER TABLE review_topic_def DROP CONSTRAINT IF EXISTS review_topic_def_version_key_key;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conname = 'review_topic_def_dim_version_key_key') THEN
        ALTER TABLE review_topic_def
            ADD CONSTRAINT review_topic_def_dim_version_key_key UNIQUE (dim, version, key);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS review_topic_def_dim
    ON review_topic_def (dim, version);
