-- 107: эталон и канарейка качества срезов «Аудита отзывов» (rag/review_slices_canary.py).
--
-- Было. Качество срезов мерили один раз — на эталоне 04.11.2026 (GOLD_0411 в
-- rag/review_slices.py): числа живут в коде, а смену модели в облаке, правку
-- определений или тихую деградацию провайдера мы увидели бы только по отметкам
-- аудиторов «не относится» — через недели.
--
-- Стало. Эталон лежит в базе (scripts/load_slice_gold.py из файлов ручной разметки;
-- сами файлы в репозиторий не кладём — в них тексты жалоб). Раз в неделю каскад
-- срезов прогоняется на постоянной выборке из эталона БЕЗ записи разметки, а точность
-- и полнота по каждому срезу ложатся сюда; «Пульс» показывает последние прогоны.
--
-- NB: знак процента в комментариях миграций не ставить — накатываются через
-- exec_driver_sql, psycopg считает его началом плейсхолдера.

-- Таблицы новые, но и они не должны вставать в очередь за чужими блокировками
-- (14.10 ALTER за долгой транзакцией подвесил вкладку).
SET lock_timeout = '3s';

-- Решения людей по жалобе: {срез: true | false}. Срез без ключа — эталона по нему нет
-- (добавили срез позже разметки), такая жалоба в его счёт не идёт.
CREATE TABLE IF NOT EXISTS review_slice_gold (
    url      text        PRIMARY KEY,
    labels   jsonb       NOT NULL,
    source   text,                                 -- какой набор разметки (имя эталона)
    added_at timestamptz NOT NULL DEFAULT now()
);

-- Прогоны канарейки. Тревога не хранится: её считает код по паре соседних прогонов
-- (review_slices_canary.alerts) — одно правило и для свежего прогона, и для истории.
CREATE TABLE IF NOT EXISTS review_slice_canary (
    run_at  timestamptz PRIMARY KEY,
    schema  text        NOT NULL,                  -- версия определений, которой мерили
    n       int         NOT NULL DEFAULT 0,        -- жалоб, по которым каскад дал решение
    metrics jsonb       NOT NULL DEFAULT '{}',     -- {срез: {tp, fp, fn, precision, recall}}
    rub     numeric(10, 2) NOT NULL DEFAULT 0,     -- траты прогона (в журнал трат разметки не идут)
    note    text                                   -- выборка, пропуски, остановка, причины тревоги
);
