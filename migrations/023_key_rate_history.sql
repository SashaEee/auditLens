-- 023: история ключевой ставки ЦБ в БД.
--
-- Было: ставка жила только внутри jsonb-кэша с TTL 6 часов и вмерзала снимком
-- в выпуск дайджеста. 27.07.2026 это дало сбой: ЦБ снизил ставку 14.25 → 14.00
-- с понедельника, но в 07:00 SOAP ещё отдавал строки по 24.07. Значение
-- закэшировалось на 6 часов и попало в выпуск дня — на главной весь день висело
-- «Ставка 14.25%» и посчитанный от неё спред «−0.75 пп» вместо верных «−0.50 пп».
--
-- Таблица решает три задачи, которых кэш решить не мог:
--   1. на экране всегда есть последнее известное значение с честной датой,
--      даже когда ЦБ недоступен (кэш в этом случае отдавал None);
--   2. видно ДАТУ вступления в силу и факт изменения — можно сказать
--      «ставка изменилась сегодня», а не показывать голое число;
--   3. аудитор может ответить «какая ставка действовала на дату проверки» —
--      раньше история скачивалась каждые 6 часов и выбрасывалась.

CREATE TABLE IF NOT EXISTS cbr_key_rate (
    rate_date  date PRIMARY KEY,          -- дата, с которой действует значение
    rate       numeric(6,2) NOT NULL,
    fetched_at timestamptz NOT NULL DEFAULT now()
);

-- выборка «текущая ставка» = самая поздняя строка не из будущего
CREATE INDEX IF NOT EXISTS cbr_key_rate_date ON cbr_key_rate (rate_date DESC);
