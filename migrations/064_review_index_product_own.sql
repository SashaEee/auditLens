-- Колонка review_index.product переходит на НАШУ разметку продукта.
--
-- ЗАЧЕМ. review_index — наша таблица, но колонка product в ней была копией
-- метки из корпуса площадки, а та неверна у 86-93 процентов обращений всех
-- банков: почти всё помечено обслуживанием юрлиц, хотя по тексту это розница.
-- Собственная разметка теперь есть (миграция 063 и измерение product), и
-- честнее положить в колонку её, чем оставлять заведомо ложное значение.
--
-- Так все восемь мест, которые уже фильтруют и группируют по i.product,
-- начинают работать по верным данным без единой правки запроса. Альтернатива —
-- переписать каждый запрос на подзапрос к разметке — дала бы ту же выдачу
-- ценой пяти разных SQL, четыре из которых не f-строки.
--
-- Исходная метка не выбрасывается: она уезжает в product_src. Она плоха как
-- истина, но остаётся свидетельством о том, что отдал источник, и по ней можно
-- восстановить прежнее поведение или измерить расхождение.
--
-- NB: знак процента в комментариях миграций не ставить (exec_driver_sql).

ALTER TABLE review_index ADD COLUMN IF NOT EXISTS product_src TEXT;

-- Разовый перенос: то, что сейчас лежит в product, это и есть метка источника.
UPDATE review_index SET product_src = product
 WHERE product_src IS NULL AND product IS NOT NULL;

COMMENT ON COLUMN review_index.product IS
    'Продукт по НАШЕЙ разметке (review_topic_def.dim=product). NULL — не отнесён.';
COMMENT ON COLUMN review_index.product_src IS
    'Метка продукта, как её отдал источник. Ненадёжна, хранится для сверки.';
