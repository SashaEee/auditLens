-- 029: таксономия тем отзывов, выведенная из корпуса, вместо списка в коде.
--
-- Что было. 21 тема и 144 подстроки, написанные руками в reviews_dash.THEMES.
-- Это не масштабируется: банковских продуктов и способов пожаловаться столько,
-- что список придётся вечно дописывать, и он всё равно отстаёт от того, как
-- пишут клиенты. Плюс он молча врал: словарь писался основами через пробел, а
-- сравнивался подстрокой, из-за чего «Скрытые комиссии» находили 160 отзывов
-- вместо 752.
--
-- Что вместо. Темы выводит модель из самого корпуса, а раскладывает по ним не
-- она, а вектор: описание темы эмбедится тем же bge-m3, что и отзывы, и
-- близость считается обычным косинусом. Модель отвечает за то, КАКИЕ бывают
-- темы, а не за разметку каждой строки — иначе разметка 169 тыс. отзывов стоила
-- бы десятки миллионов токенов и её нельзя было бы повторить.
--
-- Почему разметка хранится, а не считается на лету. Панель тем — агрегат по
-- всему рынку за 63 дня, он вызывается на каждое открытие вкладки. Ни LLM, ни
-- перебор векторов там жить не могут. Разметка делается фоном один раз и потом
-- читается обычным GROUP BY.
--
-- Ключ разметки — url, тот же, что в bankiru_review_fts (028): там уже лежат
-- банк, продукт, дата и город, поэтому агрегаты собираются одним join и не
-- требуют ничего дописывать в чужую базу, куда у нас всё равно нет прав.

CREATE TABLE IF NOT EXISTS review_topic_def (
    topic_id   SERIAL PRIMARY KEY,
    version    INTEGER NOT NULL,          -- поколение таксономии; активное — в state
    key        TEXT    NOT NULL,          -- латинский слаг, стабильная ссылка из кода/URL
    label      TEXT    NOT NULL,          -- как показываем аудитору
    descr      TEXT    NOT NULL,          -- развёрнутое описание; ИМЕННО ОНО эмбедится
    risk       TEXT,                      -- compliance | conduct | ops
    n_seed     INTEGER NOT NULL DEFAULT 0,-- на скольких жалобах тема была замечена
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (version, key)
);

-- Вектор темы держим под guard: на машинах без pgvector остальная схема должна
-- накатываться (тот же приём, что в миграциях базы знаний).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'vector') THEN
        ALTER TABLE review_topic_def
            ADD COLUMN IF NOT EXISTS embedding vector(1024);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS review_topic_label (
    url      TEXT    NOT NULL,
    topic_id INTEGER NOT NULL REFERENCES review_topic_def(topic_id) ON DELETE CASCADE,
    score    REAL    NOT NULL,            -- 1 - косинусная дистанция, 0..1
    PRIMARY KEY (url, topic_id)
);

-- Нормированная оценка: на сколько своих стандартных отклонений отзыв ближе к
-- теме, чем средний отзыв корпуса.
--
-- Зачем. Сырой косинус между темой и жалобой сравнивать между темами нельзя:
-- замер показал, что все оценки сбиты в 0.50–0.65, а темы различаются
-- «притягательностью». «Задержки и неисполнение операций» цепляли 103 тыс.
-- отзывов из 169 тыс. просто потому, что формулировка близка к любой жалобе.
-- Абсолютный порог тут не работает ни при каком значении: при 0.45 размечено
-- 99 отзывов из 100, при 0.60 выброшены две трети. Ровно та же болезнь, что у косинусной
-- дистанции в поиске, и лечится так же — относительной мерой вместо абсолютной.
ALTER TABLE review_topic_label ADD COLUMN IF NOT EXISTS z REAL;

-- Место темы среди тем этого отзыва (1 = ближайшая), по нормированной оценке.
-- Порога недостаточно: он отсекает по величине, а не по месту, и восьмая по
-- близости тема отзыва проходит наравне с первой. Замер точности (доля отзывов
-- темы, где встречается её бесспорное слово): ранг 1 даёт 0.65, ранг 2 — 0.53,
-- ранг 3 — 0.46, а без ограничения ранга всего 0.16.
--
-- NB: знак процента в комментариях миграций НЕ СТАВИТЬ, даже внутри кавычек.
-- Миграции накатываются через exec_driver_sql, а psycopg считает этот знак
-- началом плейсхолдера и падает ещё до отправки запроса в базу.
ALTER TABLE review_topic_label ADD COLUMN IF NOT EXISTS rn SMALLINT;
CREATE INDEX IF NOT EXISTS review_topic_label_topic_z
    ON review_topic_label (topic_id, z DESC);

-- агрегат идёт «по теме за период», поэтому ведущий столбец — topic_id
CREATE INDEX IF NOT EXISTS review_topic_label_topic ON review_topic_label (topic_id);

-- какое поколение таксономии считается активным и когда размечали
CREATE TABLE IF NOT EXISTS review_topic_state (
    k          TEXT PRIMARY KEY,
    v          TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
