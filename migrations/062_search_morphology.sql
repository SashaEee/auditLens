-- Смысловой поиск: «Лазейки» и витрина «Рынок».
--
-- ЗАЧЕМ. Обе вкладки искали подстрокой: LOWER(title) LIKE '...' у лазеек,
-- ILIKE у витрины. Отсюда две жалобы аудиторов, которые на самом
-- деле об одном:
--   • «задаёшь вклад — выдаются ломбарды, карты» и «эскроу — записей не
--     найдено»: слово, встреченное в теле статьи в постороннем контексте,
--     поднимало запись наравне с той, что действительно про это;
--   • «дебетовые карты — ничего не найдено» на витрине: подстроки «дебетовые
--     карты» нет в названии «Дебетовая карта», хотя это одно и то же.
--
-- Русский словарь Postgres приводит слово к основе, поэтому «вклады», «вкладу»
-- и «вклад» становятся одной лексемой, а «дебетовые карты» совпадает с
-- «Дебетовой картой». Это то же средство, которым уже ищут «База знаний» и
-- «Отзывы» — новых зависимостей не появляется.
--
-- CAST в regconfig обязателен: без него выбирается перегрузка
-- to_tsvector(text, text), которая не IMMUTABLE, и генерируемая колонка
-- создаваться откажется.

-- ── Лазейки ─────────────────────────────────────────────────────────────────
-- Вес важнее самого попадания. Заголовок и краткое изложение — это УТВЕРЖДЕНИЕ
-- лазейки, то, ради чего запись заведена. Тело статьи первоисточника — просто
-- материал, где искомое слово может стоять в проходной фразе («кредитная
-- организация» на запрос «кредит» — ровно тот случай, о котором сообщали).
-- Поэтому A для заголовка, B для изложения, C для довода классификатора и D
-- для сырого текста: ts_rank_cd сам расставит их по местам.
ALTER TABLE loophole_record
    ADD COLUMN IF NOT EXISTS search_tsv tsvector
    GENERATED ALWAYS AS (
        setweight(to_tsvector(CAST('russian' AS regconfig), coalesce(title, '')), 'A')
     || setweight(to_tsvector(CAST('russian' AS regconfig), coalesce(snippet, '')), 'B')
     || setweight(to_tsvector(CAST('russian' AS regconfig), coalesce(verdict_reason, '')), 'C')
        -- Обрезка на 200 КБ — страховка от предела размера tsvector (1 МБ).
        -- Самая длинная статья в таблице сейчас 31 КБ, запас пятикратный.
     || setweight(to_tsvector(CAST('russian' AS regconfig), left(coalesce(raw_text, ''), 200000)), 'D')
    ) STORED;

CREATE INDEX IF NOT EXISTS loophole_record_tsv_gin
    ON loophole_record USING GIN (search_tsv);

