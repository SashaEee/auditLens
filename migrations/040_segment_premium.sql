-- 040: доклассифицировать премиальные продукты, которых правило не видело.
--
-- Сверка сегмента по названию с сегментом, вычитанным LLM из самого тарифа
-- (проверка SEGMENT_MISMATCH), показала systematic-промах: правило знало
-- «премиальная», «привилегия», «премьер», но не знало слова «Премиум» —
-- «Пакет услуг "Премиум"», «На новый автомобиль — Премиум» лежали в массовом
-- сегменте и ранжировались рядом с обычными продуктами.
-- Нормализатор уже исправлен; здесь чиним накопленное.
-- NB: одиночного знака процента в файле быть не должно (exec_driver_sql).

UPDATE product_offer
   SET segment = 'premium'
 WHERE COALESCE(segment, 'mass') = 'mass'
   AND title ~* 'премиум';
