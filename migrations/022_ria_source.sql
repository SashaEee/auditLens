-- РИА добавлено в сбор новостей дашборда (digest/news.py). Отдельно регистрируем
-- домен в source_trust, чтобы статьи РИА, которые прочитает ИИ-аналитик, попадали
-- в базу знаний с честным доверием, а не оседали «блогом» с весом 0.30 (ниже
-- порога поиска 0.50). РИА — госагентство, прямой аналог ТАСС (0.85 в 007),
-- поэтому тот же вес. realty.ria.ru уже был press 0.80 — приводим и основной домен.

INSERT INTO source_trust(kind, domain, weight, notes) VALUES
    ('press', 'ria.ru', 0.85, 'РИА Новости (госагентство)')
ON CONFLICT (kind, domain) DO UPDATE SET weight = EXCLUDED.weight, notes = EXCLUDED.notes;
