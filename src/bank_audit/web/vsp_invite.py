"""Письмо-приглашение в бета-тест раздела «Аудит сети ВСП».

Цифры подставляет вызывающий из текущего расчёта вкладки (brief/map), шаблон — общий
для писем AuditLens (mail_templates): светлая карточка, логотип, кнопка, подвал с причиной.
"""
from __future__ import annotations

from . import mail_templates as T

NOTE = "Ответ на это письмо не дойдёт до команды — пишите в AuditLens через «Обратную связь» внизу меню."


def _n(x) -> str:
    return f"{int(x):,}".replace(",", " ") if isinstance(x, (int, float)) else "—"


def render(name: str | None, stats: dict) -> dict:
    """name — отображаемое имя («Светлана Фукс»); stats: read, stories, reviews, up (растущих способов действия),
    hot (очагов), points."""
    base = T.app_base()
    url = f"{base}/#vsp"
    first = T.first_name(name)
    hello = f"{first}, вы в бета-тесте" if first else "Вы в бета-тесте"
    subject = "Вы в бета-тесте: «Аудит сети ВСП» в AuditLens"
    pre = "Новый раздел: что массово повторяется в сети ВСП, где это сгущается и что запросить из данных банка"
    intro = (f"Мы собрали отзывы клиентов обо всех отделениях Сбера с 2ГИС и Яндекс Карт — "
             f"{_n(stats.get('reviews'))} — и дали модели прочитать каждый. Она ищет не «плохой сервис» и не "
             "отдельные жалобы, а массовое: один и тот же приём у многих клиентов, в нескольких отделениях "
             "одного города — оформили без согласия, выдали один продукт под видом другого, работали "
             "в телефоне клиента, недодали наличные.")
    third = ((_n(stats.get("up")), "способов действия растут или появились") if stats.get("up") is not None
             else (_n(stats.get("hot")), "очагов по городам и ГОСБ") if stats.get("hot") is not None else None)
    body = (T._eyebrow("Бета-доступ · новый раздел", T.BRAND)
            + T._h1(hello, "«Аудит сети ВСП» открыт вам одним из первых")
            + T._p(T._e(intro), size=15, top=18)
            + T._kpis([(_n(stats.get("read")), "отзывов прочитала модель"),
                       (_n(stats.get("stories")), "историй о возможных нарушениях")] + ([third] if third else []))
            + T._card("Главное", "За пять минут: что идёт, где сгущается, кого смотреть",
                      "Способ действия, который растёт, сильные случаи с дословной цитатой клиента "
                      "и готовый запрос данных банка.", accent=T.BRAND)
            + T._card("Схемы", "Что растёт, что новое, что ушло",
                      "Способы действия по кварталам и очаги — города и ГОСБ, где один приём повторяется "
                      "в нескольких отделениях.", accent=T.HAIR, top=12)
            + T._card("Где проверить", "Карта и три полки",
                      "Где клиентов с тяжёлыми историями больше ожидаемого; отделения, где виден один почерк; "
                      "отдельные тяжёлые случаи. У каждого — основание и полный отзыв клиента.", accent=T.HAIR, top=12)
            + T._card("Истории", "Все случаи и вид «Изнутри»",
                      "Фильтры по региону, ГОСБ и тому, что произошло; выгрузка в Excel, листы проверки "
                      "и запросы данных в Word.", accent=T.HAIR, top=12)
            + T._p(T._e("Это бета: раздел ещё меняется. Отзывы — слова клиентов, а не установленные факты, "
                        "поэтому у каждой истории есть проверка: полный текст, подсвеченная цитата "
                        "и ссылка на страницу отзывов отделения."), color=T.INK3, size=14, top=22)
            + T._btn("Открыть «Аудит сети ВСП»", url)
            + T._p(T._e("Раздел — в меню слева, в группе «Анализ». Если что-то покажется странным или, "
                        "наоборот, полезным — нажмите «Обратная связь» внизу меню: читаем всё."),
                   color=T.INK3, size=13, top=22))
    reason = "Вы получили это письмо, потому что вам открыли бета-доступ к разделу «Аудит сети ВСП»."
    lines = [intro, "",
             f"Модель прочитала {_n(stats.get('read'))} отзывов и нашла {_n(stats.get('stories'))} историй "
             "о возможных нарушениях"
             + (f"; {third[0]} {third[1]}." if third else "."), "",
             "Главное — за пять минут: что идёт по сети, где сгущается, кого смотреть и что запросить.",
             "Схемы — способы действия по кварталам и очаги по городам и ГОСБ.",
             "Где проверить — карта «больше ожидаемого» и три полки с основаниями.",
             "Истории — все случаи и вид «Изнутри»; Excel, листы проверки и запросы данных.", "",
             "Это бета: раздел ещё меняется. Отзывы — слова клиентов, а не установленные факты.",
             "Обратная связь — кнопка внизу меню AuditLens."]
    return {"subject": subject, "preheader": pre, "url": url,
            "html": T.layout(preheader=pre, title=subject, body=body, reason=reason, note=NOTE,
                             section="Аудит сети ВСП"),
            "text": T._text("Бета-доступ", f"{hello}: «Аудит сети ВСП»", lines, "Открыть раздел", url, reason, NOTE),
            "thread": "vsp-beta"}
