"""Персональные данные на входе ИИ-помощника: запрос о конкретном частном лице
не уходит ни в модель, ни в поиск и хранится только замаскированным.

Почему так: инструмент работает в облаке, где по правилам площадки персональные
данные запрещены, а каждый вопрос сохраняется в общей базе и уходит во внешнюю
модель и интернет-поиск. 2026-10 в разделах были запросы «всё о <ФИО> <дата
рождения>, её деятельности, связях» — сбор сведений о человеке без основания и
цели. Раньше их ничто не останавливало.

Что считаем запросом о частном лице (точность важнее полноты — «что заявил
Греф» или «банк Иванова» останавливать нельзя):
• полное ФИО с отчеством (в любом падеже, в любом порядке) ВМЕСТЕ с датой
  рождения, паспортом, ИНН физлица, СНИЛС, телефоном или почтой;
• или полное ФИО вместе с «досье»-формулировкой: «всё о», «найди информацию о»,
  «связи», «где зарегистрирован», «пробей», «биография».
Одно ФИО без этого — не повод (новости о руководителях банков, авторы статей).
"""
from __future__ import annotations

import json
import re
from typing import AsyncIterator

_W = r"[А-ЯЁа-яё]+"
# отчество во всех падежах: Иванович(а|у|ем|е), Раисовна(ы|е|у|ой), Ильинична, Кузьминична
_PATR = (r"(?:[А-ЯЁа-яё]+(?:ович|евич|ьич)(?:а|у|ем|е)?"
         r"|[А-ЯЁа-яё]+(?:овн|евн|ичн|иничн)(?:а|ы|е|у|ой))")
# «Фамилия Имя Отчество» или «Имя Отчество Фамилия»; слова — с заглавной или все строчные
_FIO = re.compile(rf"(?<![А-ЯЁа-яё])(?:{_W}\s+{_W}\s+{_PATR}|{_W}\s+{_PATR}\s+{_W})(?![А-ЯЁа-яё])")
_DOB = re.compile(r"(?<!\d)(?:0?[1-9]|[12]\d|3[01])[./-](?:0?[1-9]|1[0-2])[./-](?:19\d{2}|20[01]\d)(?!\d)"
                  r"|(?<!\d)(?:19\d{2}|20[01]\d)\s*(?:г\.?\s*р\.?|года\s+рождения)", re.I)
_PASSPORT = re.compile(r"паспорт\w*\s*(?:серии\s*)?[:№]?\s*\d[\d\s№]{0,14}\d"
                       r"|(?<!\d)\d{2}\s?\d{2}\s?№?\s?\d{6}(?!\d)", re.I)
_INN12 = re.compile(r"(?<!\d)\d{12}(?!\d)")
_SNILS = re.compile(r"(?<!\d)\d{3}-\d{3}-\d{3}[ -]\d{2}(?!\d)")
_PHONE = re.compile(r"(?<!\d)(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)")
_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_DOSSIER = re.compile(r"\b(?:вс[её]\s+(?:о|об|про)|информаци\w*\s+(?:о|об|по|на)|данны\w*\s+(?:о|об|по|на)"
                      r"|связ(?:и|ях|ей)\b|где\s+(?:зарегистрир|работает|жив[её]т|прописан)"
                      r"|пробе\w*|биографи\w*|досье|найди\w*\s+(?:человека|клиента|сотрудника|лицо))", re.I)

_IDS = (("дата рождения", _DOB), ("паспорт", _PASSPORT), ("ИНН", _INN12), ("СНИЛС", _SNILS),
        ("телефон", _PHONE), ("почта", _EMAIL))

REFUSAL = (
    "**Этот запрос AuditLens выполнить не может: в нём персональные данные частного лица.**\n\n"
    "AuditLens работает в облаке, где персональные данные запрещены правилами площадки, а каждый "
    "запрос уходит во внешнюю модель и интернет-поиск. Поиск сведений о конкретном человеке "
    "({found}) — это обработка его персональных данных без основания и цели (152-ФЗ), поэтому "
    "запрос не отправлен и сохранён без ФИО и реквизитов.\n\n"
    "Проверки конкретных лиц проводятся через штатные каналы банка — службу безопасности и "
    "внутренние системы. В AuditLens можно спросить о схеме или процессе без привязки к человеку: "
    "например, «какие признаки дроп-счетов встречаются в жалобах клиентов» или «как мошенники "
    "используют данные клиентов при переоформлении карт».")


def check(text: str) -> list[str] | None:
    """Что в запросе указывает на конкретное частное лицо, или None — запрос можно выполнять."""
    t = text or ""
    if not _FIO.search(t):
        return None
    found = ["ФИО"] + [name for name, rx in _IDS if rx.search(t)]
    if len(found) > 1 or _DOSSIER.search(t):
        return found
    return None


def mask(text: str) -> str:
    """Текст для хранения. Запрос о частном лице — без ФИО, дат и реквизитов.
    В остальных — только однозначные идентификаторы (телефон, почта, СНИЛС):
    десятизначное число бывает ИНН компании, а ФИО — руководителем банка из
    новости, и маскировать их в обычном вопросе нельзя."""
    t = text or ""
    if check(t):
        for name, rx in _IDS:
            t = rx.sub(f"[{name}]", t)
        return _FIO.sub("[ФИО]", t)
    for name, rx in (("телефон", _PHONE), ("почта", _EMAIL), ("СНИЛС", _SNILS)):
        t = rx.sub(f"[{name}]", t)
    return t


def masked_or_none(text: str) -> str | None:
    """Замаскированный текст, если в нём было что маскировать, иначе None."""
    m = mask(text)
    return m if m != (text or "") else None


async def stream_refusal(found: list[str]) -> AsyncIterator[str]:
    """Ответ в том же потоке событий, что и обычный быстрый ответ."""
    yield json.dumps({"type": "mode", "value": "quick"})
    yield json.dumps({"type": "text", "chunk": REFUSAL.format(found=", ".join(found))},
                     ensure_ascii=False)
    yield json.dumps({"type": "done"})
