def section_prompt(section: str, plan, question: str, labels: dict[str, str],
                   *, facts_text: str, prior_text: str = "",
                   gaps_text: str = "", brief=None, order=None) -> str:
    parts = [_common(plan, question, labels), ""]
    mode = checks_mode(plan)
    short_checks = section == "checks" and mode == "short"
    if brief is not None:
        parts += [brief.render(None if section in LEAD else section,
                               sections=not short_checks), ""]
    if short_checks:
        parts.append(_CHECKS_SHORT_SCOPE)
    elif section in LEAD:
        parts.append(_LEAD_SCOPE)
    else:
        parts.append(_BODY_SCOPE)
    rules = section
    if section.startswith(TOPIC):
        rules = "topic"
    elif section == "checks" and mode == "short":
        rules = "checks_short"
    elif section == "summary" and mode == "none":
        rules = "summary_plain"
    parts += ["", _SECTION_RULES[rules]]
    if section == "voice" and not complaints_asked(plan, question):
        parts += ["", _VOICE_SUPPORTING]
    if section == "checks" and mode == "full":
        parts += ["", _CHECKS_LOOPHOLES if "loopholes" in (order or ()) else _CHECKS_NO_LOOPHOLES]
    if section in LEAD:
        # Без этой строки писатель резюме однажды начал с рассуждения вслух:
        # «Нет единого раздела, который мне назначен… мне нужно написать
        # «Резюме»» (прогон 11.11) — в перечне разделов брифа его раздела нет.
        parts += ["", f"ТВОЙ РАЗДЕЛ — «{titles(plan).get(section, section)}». Разделы "
                      "из перечня выше уже написаны. Начинай сразу с содержания: без "
                      "заголовка, без вступления о том, что и по чему ты пишешь."]
        if prior_text:
            parts += ["", "ТЕЛО ОТЧЁТА (уже написано, опирайся на него):", prior_text]
        if gaps_text:
            parts += ["", "ЧТО НЕ УДАЛОСЬ УСТАНОВИТЬ:", gaps_text]
        parts += ["", "ФАКТЫ ОТЧЁТА (все; для якорей):", facts_text]
    else:
        parts += ["", "ФАКТЫ РАЗДЕЛА:", facts_text]
    return "\n".join(parts)


