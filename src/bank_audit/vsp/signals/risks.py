_COMPILED = {t.key: ([re.compile(p) for p in t.any_of], [re.compile(p) for p in t.also],
                     [re.compile(p) for p in t.unless]) for t in TYPES}


def norm(text: str | None) -> str:
    return (text or "").lower().replace("ё", "е")


def match(text: str | None) -> list[tuple[str, str]]:
    """[(тип, цитата вокруг совпадения)] — самое тяжёлое первым."""
    t = norm(text)
    if len(t) < 15:
        return []
    out = []
    for rt in TYPES:
        anys, alsos, unless = _COMPILED[rt.key]
        m = next((m for rx in anys for m in [rx.search(t)] if m), None)
        if not m:
            continue
        if alsos and not any(rx.search(t) for rx in alsos):
            continue
        if unless and any(rx.search(t) for rx in unless):
            continue
        out.append((rt.key, quote(text or "", m.start(), m.end())))
    return sorted(out, key=lambda x: -BY_KEY[x[0]].severity)


def quote(text: str, a: int, b: int, pad: int = 90) -> str:
    """Кусок исходного текста вокруг совпадения (по границам слов)."""
    s, e = max(0, a - pad), min(len(text), b + pad)
    while s > 0 and text[s - 1] not in " \n":
        s -= 1
    while e < len(text) and text[e] not in " \n":
        e += 1
    return ("…" if s > 0 else "") + text[s:e].strip() + ("…" if e < len(text) else "")
