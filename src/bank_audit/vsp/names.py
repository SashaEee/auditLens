"""Имена сотрудников в текстах отзывов: найти (фильтр «упомянут сотрудник»).

Во вкладке тексты показываются как есть; маска нужна, чтобы отличить отзыв, где назван
конкретный сотрудник, и для выгрузок за пределы вкладки, если понадобится.
Ловим то, чем клиенты называют сотрудников: распространённые имена в любом падеже
(«менеджеру Анне», «с Ольгой»), отчества («Ольга Викторовна»), уменьшительные
(«Настя», «Саша»). Точность важнее полноты нет: лучше спрятать лишнее слово, чем
показать имя. Фамилии отдельно не ищем — они почти всегда идут рядом с именем.
"""
from __future__ import annotations

import re

# основы имён: к основе допускаются окончания падежей (Анн-а/-е/-ы/-у/-ой, Олег-а/-у/-ом)
_STEMS = """
александр алексе анатоли андре антон аркади арсени артем артур богдан борис вадим валенти валери
васили виктор виталь владимир владислав всеволод вячеслав геннади георги герман глеб григори
дании даниил денис дмитри евгени его ефим захар иван игор илья ильдар ильнур ильназ кирилл констант
лев льв леонид макар максим марат матве миха михаил назар никит никола олег павел павл петр родион
роман руслан рустам семен серге станислав степан тагир тимофе тимур федор филипп эдуард эльдар юри
яков ярослав ринат рамиль айдар азат альберт альфред
александр алин алис алл альбин анастаси анжел анжелик ангелин анн антонин анфис ари валентин
валери варвар вер веро вероник виктори виолетт галин дарь дарин диан дин евгени екатерин елен
елизавет жанн зарем зинаид злат зо зульфи ильмир инг инн ирин камил карин кир кристин ксени лар
лейл лиан лид лили лилиан ли любов людмил ляйсан маргарит марин мари марьям милан мил надежд наталь
наталь нелли ник нин оксан ольг полин рамил регин ренат римм ри роз светлан снежан софь софи
стелл тамар тать ульян фатим эвелин элин эльвир эльмир эльз юли ян
настя наст саш маш даш кат кать лен ол оль тан тань юл ир иришк натах наташ ник надюш галочк
серёж сереж дим леш лёш миш паш вов вань ром жен костя кост толик слав влад вит артём
"""
_STEM_SET = sorted({s for s in _STEMS.split() if len(s) >= 3}, key=len, reverse=True)
# только падежные окончания: «Верните» и «Милые» — не имена, «Вера» и «Мила» — имена.
# Короткой основе (до 4 букв) окончание обязательно: «Свет», «Лев» сами по себе — обычные слова
_END = r"(?:а|я|е|и|ы|у|ю|ой|ей|ом|ем|ём|ою|ею|й|ь|ью|ич)"
_LONG = [x for x in _STEM_SET if len(x) >= 5]
_SHORT = [x for x in _STEM_SET if len(x) < 5]
_NAME = re.compile(r"(?<![А-ЯЁа-яё])(?:(?:" + "|".join(_LONG) + r")" + _END + r"?|(?:" + "|".join(_SHORT) + r")"
                   + _END + r")(?![А-ЯЁа-яё])", re.I)
_PATR = re.compile(r"(?<![А-ЯЁа-яё])[А-ЯЁ][а-яё]+(?:ович|евич|ьич|овн|евн|ичн|иничн)[а-яё]{0,3}(?![А-ЯЁа-яё])")
# «менеджер(у) Х», «кассир Х», «сотрудник(ца) Х» — следующее слово с заглавной
_ROLE = re.compile(r"(?i:(?:менеджер|специалист|сотрудни|кассир|консультант|операционист|девушк|молод\w+ человек"
                   r"|управляющ|директор|руководител|администратор|оператор)\w*)\s+([А-ЯЁ][а-яё]{2,})")

MASK = "[имя]"


def mask_names(text: str | None) -> str | None:
    """Текст с именами сотрудников, заменёнными на «[имя]»."""
    if not text:
        return text
    t = _PATR.sub(MASK, text)
    t = _ROLE.sub(lambda m: m.group(0)[: m.start(1) - m.start(0)] + MASK, t)

    def name(m: re.Match) -> str:
        w = m.group(0)
        # имя пишут с заглавной; строчное «вера», «надежда», «роман», «лев», «любовь» — обычные слова
        return MASK if w[0].isupper() else w
    return _NAME.sub(name, t)


def has_name(text: str | None) -> bool:
    return bool(text) and mask_names(text) != text
