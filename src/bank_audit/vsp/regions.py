def tile_grid(centroids: dict[str, tuple[float, float]], cols: int = 18, rows: int = 11) -> dict[str, tuple[int, int]]:
    """Плиточная карта из данных: центр субъекта (средние координаты его ВСП) → клетка сетки.
    Долгота сжимается косинусом широты, каждый субъект — в ближайшую свободную клетку
    (сначала самые «тесные»: Москва, области центра). Раскладка устойчива к добавлению ВСП."""
    if not centroids:
        return {}
    pts = {k: (lon * math.cos(math.radians(58)), lat) for k, (lat, lon) in centroids.items()}
    xs, ys = [p[0] for p in pts.values()], [p[1] for p in pts.values()]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)

    def cell(p):
        x = (p[0] - x0) / ((x1 - x0) or 1) * (cols - 1)
        y = (y1 - p[1]) / ((y1 - y0) or 1) * (rows - 1)
        return x, y
    want = {k: cell(p) for k, p in pts.items()}
    # плотность: сколько субъектов претендует на окрестность — плотные ставим первыми
    order = sorted(want, key=lambda k: -sum(1 for o in want.values()
                                            if abs(o[0] - want[k][0]) < 1.5 and abs(o[1] - want[k][1]) < 1.5))
    taken: dict[tuple[int, int], str] = {}
    out: dict[str, tuple[int, int]] = {}
    for k in order:
        x, y = want[k]
        best = min(((c, r) for c in range(cols) for r in range(rows) if (c, r) not in taken),
                   key=lambda cr: (cr[0] - x) ** 2 + (cr[1] - y) ** 2)
        taken[best] = k
        out[k] = best
    return out
