"""Словарь «Аудита отзывов»: что значат слова, которыми о жалобах говорят вкладка,
выгрузка в Excel и ИИ-помощник.

Зачем отдельный модуль (04.11.2026). Определение жалобы разошлось с подсчётом: все
счётчики вкладки, сигналов и обзора считают жалобой отзыв, который LLM-разметка
отнесла к претензиям — kind complaint или mixed (review_codebook.COMPLAINT_KINDS,
условие reviews_dash._CMP), а выгрузка в Excel и инструмент ИИ писали «отзывы с
оценкой 1–2★». Аудитор читал в выгрузке одно, во вкладке другое, ИИ пересказывал
третье. Оценка в счёте не участвует: отзыв с одной звездой без претензии (вопрос,
мусор, копия) жалобой не считается, смешанный — претензия вместе с похвалой —
считается.

Так же разошлись слова поиска: с 03.11 выгрузка отдаёт ровно найденный вкладкой
список, а лист «О выгрузке» ещё писал «поиск по смыслу в выгрузку не входит».
Поэтому числа в формулировках (сколько похожих по смыслу добавляет поиск, потолок
словесной части) берутся из reviews_dash, где задан сам набор, а названия особых
срезов — из review_slices: текст не отстанет от кода.

Формулировки — и для человека, и для модели: инструменты ИИ кладут их в ответ
рядом с числами, чтобы модель называла число так же, как вкладка.
"""
from __future__ import annotations

from . import review_codebook as cb

# Что считается жалобой во всех счётчиках — тот же перечень, что у разметки.
COMPLAINT_KINDS = cb.COMPLAINT_KINDS

COMPLAINT = (
    "Жалоба — отзыв с любой площадки, который ИИ при разметке отнёс к претензиям к банку, "
    "в том числе смешанный: претензия вместе с похвалой. Считается по тексту отзыва, а не по "
    "оценке: похвала, вопросы, мусор и копии одного отзыва в число жалоб не входят, как и "
    "свежие отзывы, которые ещё не размечены.")

# Для мест, где длинный текст не помещается: поле «как считали» в ответе инструмента.
COMPLAINT_SHORT = (
    "жалобы — отзывы со всех площадок, которые ИИ отнёс к претензиям (в том числе "
    "смешанные: претензия вместе с похвалой); по тексту, а не по звёздам; без похвалы, "
    "вопросов, мусора, копий и ещё не размеченных")

THEME = (
    "Тема — главная проблема жалобы по кодификатору AuditLens. Она у жалобы одна, поэтому "
    "доли тем в сумме дают 100%, а число по теме — жалобы, где она главная. Где проблема "
    "названа дополнительной, жалоба в это число не входит.")

DIRECTION = (
    "Направление — участок, который проверяет аудитор: ипотека, кредитные карты, зарплатные "
    "проекты, эквайринг и т. п. В «Аудите отзывов» направлению обычно соответствует продукт "
    "или особый срез в фильтре продукта, а не тема: тема говорит, что случилось, направление — "
    "с каким продуктом или процессом.")


def _num(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def _caps() -> tuple[int, int]:
    """(до скольких похожих по смыслу, потолок словесной части) — из самого поиска."""
    from . import bankiru_fts as fts
    from . import reviews_dash as rd
    return int(rd.SENSE_CAP), int(fts.NEAR_CAP)


def by_words() -> str:
    _sense, cap = _caps()
    return ("Со словами запроса — все жалобы по фильтрам вкладки, где значимые слова запроса "
            "стоят рядом, с любыми окончаниями (сокращения и синонимы раскрываются); фраза в "
            "кавычках ищется дословно, слово с минусом исключает жалобы с ним. Это полный "
            "счёт, и «нашлось N жалоб» — именно это число; при очень частых словах счёт "
            f"идёт по {_num(cap)} самым подходящим, и у числа стоит «+».")


def by_sense() -> str:
    cap, _words = _caps()
    return (f"По смыслу — до {cap} жалоб, ближайших к запросу по смыслу, в тексте которых слов "
            "запроса нет. Это примеры, а не счёт: сколько всего таких жалоб, поиск по смыслу не "
            "говорит, и к «нашлось N» их не прибавляют.")


def search_scope() -> str:
    """Что отдаёт поиск, одной строкой: фильтры выгрузки, подписи к числу."""
    cap, _words = _caps()
    return f"все жалобы со словами запроса и до {cap} похожих по смыслу"


def slice_text() -> str:
    from . import review_slices as rs
    names = ", ".join(f"«{label}»" for label in rs.LABELS.values())
    return ("Срез — жалобы по фильтрам «Аудита отзывов»: банк, продукт, тема, признак, площадка, "
            "город, период «с — по». Вкладка, выгрузка и ИИ-помощник считают один и тот же срез "
            f"одинаково. Особые срезы в списке продуктов — {names} — не продукты договора, а "
            "сюжеты: жалобы в них отбирает отдельная разметка ИИ, и данные по ним есть с начала "
            "этой разметки.")


_TERMS = {"жалоба": lambda: COMPLAINT, "тема": lambda: THEME,
          "со словами запроса": by_words, "по смыслу": by_sense,
          "срез": slice_text, "направление": lambda: DIRECTION}
NAMES = tuple(_TERMS)


def term(name: str) -> str:
    """Формулировка по названию; неизвестное название — ошибка разработчика, не пустая строка."""
    return _TERMS[name]()


def terms(*names: str) -> dict[str, str]:
    """{название: формулировка} — для ответа инструмента ИИ. Без аргументов — весь словарь."""
    return {n: term(n) for n in (names or NAMES)}
